import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import QRCode from 'qrcode';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const businessConfigPath = path.join(rootDir, 'config', 'business.json');
const reviewsDataPath = path.join(rootDir, 'data', 'reviews.json');
const publicDir = path.join(rootDir, 'public');
const assetsDir = path.join(publicDir, 'assets');

// Ensure directories exist
fs.mkdirSync(assetsDir, { recursive: true });

// Read config & reviews
const configRaw = fs.readFileSync(businessConfigPath, 'utf8');
const config = JSON.parse(configRaw);

const reviewsRaw = fs.readFileSync(reviewsDataPath, 'utf8');
const reviews = JSON.parse(reviewsRaw);

const targetUrl = config.business?.targetUrl || 'https://nikhil-verma22.github.io/auto_review/';
console.log(`Generating QR assets for target URL: ${targetUrl}`);

// 1. Generate High-Res PNG (1024x1024)
const pngPath = path.join(assetsDir, 'qr-code.png');
await QRCode.toFile(pngPath, targetUrl, {
  type: 'png',
  width: 1024,
  margin: 2,
  errorCorrectionLevel: 'H',
  color: {
    dark: '#0f172a', // Deep slate navy for premium contrast
    light: '#ffffff'
  }
});
console.log(`✓ High-Res PNG QR Code generated at: ${pngPath}`);

// 2. Generate Scalable Vector SVG
const svgPath = path.join(assetsDir, 'qr-code.svg');
const svgString = await QRCode.toString(targetUrl, {
  type: 'svg',
  margin: 2,
  errorCorrectionLevel: 'H',
  color: {
    dark: '#0f172a',
    light: '#ffffff'
  }
});
fs.writeFileSync(svgPath, svgString, 'utf8');
console.log(`✓ Vector SVG QR Code generated at: ${svgPath}`);

// 3. Generate Pre-Bundled Data JS (window.SMART_CONNECT_DATA) for <50ms instant loading
const bundlePath = path.join(assetsDir, 'data-bundle.js');
const bundleContent = `/**
 * Pre-bundled business configuration and review pool
 * Auto-generated by scripts/generate_qr_assets.mjs
 * Generated at: ${new Date().toISOString()}
 */
window.SMART_CONNECT_DATA = ${JSON.stringify({
  business: config.business,
  categories: config.categories,
  reviews: reviews,
  generatedAt: new Date().toISOString()
}, null, 2)};
`;
fs.writeFileSync(bundlePath, bundleContent, 'utf8');
console.log(`✓ Data bundle generated at: ${bundlePath} (${reviews.length} total reviews bundled)`);

console.log('✨ All QR & data assets generated successfully!');
